"""The evidence report, three ways: index.html (to read and share), evidence.md (to diff and review),
evidence.json (for CI and other tools). All three come from the same data.
"""

import json
from collections import Counter
from datetime import datetime, timezone
from pathlib import Path

from aiquality import __version__
from aiquality.compliance.assessment import LABELS, Assessment
from aiquality.compliance.frameworks import RISK_LEVELS

TEMPLATE = Path(__file__).parent / "report_template.html"
DISCLAIMER = ("Evidence to support an assessment, not a compliance decision. Control titles are short summaries: "
              "the linked texts are the ones that count. Controls outside the tool depend on an organisation's processes.")


def report_data(assessment: Assessment) -> dict:
    record, gate = assessment.record, assessment.record.gate_decision or {}
    categories = Counter(o.get("category") or "uncategorised" for o in record.outcomes)
    return {
        "team": assessment.team,
        "description": record.description,
        "risk_level": assessment.risk_level,
        "configured": assessment.configured_level,
        "levels": list(RISK_LEVELS),
        "labels": LABELS,
        "generated_by": f"aiquality {__version__}",
        "disclaimer": DISCLAIMER,
        "run": {
            "id": record.run_id, "created_at": _when(record.created_at), "commit": record.git_commit, "mode": record.run_mode,
            "command": record.command, "agent_version": record.agent_version,
            "golden_set": f"{record.golden_set_name} {record.golden_set_version}",
            "cases": f"{record.case_count} cases run: " + ", ".join(f"{n} {c.replace('_', ' ')}" for c, n in sorted(categories.items())),
            "gate": f"Release gate: {gate['decision']}" if gate else f"No release gate ({record.command})",
            "gate_reason": (gate.get("failures") or ["every blocking bar met"])[0] if gate else "",
        },
        "frameworks": [{"key": f.key, "name": f.name, "source": f.source, "link": f.link, "note": f.note}
                       for f in assessment.frameworks],
        "controls": [{
            "framework": r.framework.key, "framework_name": r.framework.name, "anchor": r.anchor,
            "id": r.control.id, "title": r.control.title, "asks": r.control.asks,
            "applies_when": list(r.control.applies_when), "link": r.control.link, "partial": r.control.partial,
            "note": r.control.note, "outside": r.control.outside_the_tool, "summary": r.summary(),
            "labels": r.labels,
            "evidence": [{"name": e.name, "found": e.found, "met": e.met, "summary": e.summary, "facts": e.facts}
                         for e in r.evidence],
        } for r in assessment.results],
    }


def render_markdown(assessment: Assessment) -> str:
    data, level = report_data(assessment), assessment.risk_level
    run = data["run"]
    counts = assessment.count()
    lines = [f"# Evidence report: {data['team']}", "", f"_{DISCLAIMER}_", "",
             f"Run {run['id']} ({run['mode']} answers), {run['created_at']}, commit {run['commit'] or 'unknown'}. "
             f"{run['golden_set']}, {run['cases']}. {run['gate']}"
             + (f": {run['gate_reason']}" if run["gate_reason"] else "") + ".", "",
             (f"Risk level: **{level}** (team.yaml). " if level == assessment.configured_level else
              f"Risk level: **{level}**, a what-if (team.yaml says {assessment.configured_level}). ") + ", ".join(f"{counts[k]} {LABELS[k].lower()}" for k in LABELS) + ".", ""]
    shown = assessment.not_shown()
    if shown:
        lines += ["## Not shown to be met", ""]
        lines += [f"- **{r.framework.name} {r.control.id}**, {r.control.title}: {r.summary()}" for r in shown]
        lines.append("")
    for framework in assessment.frameworks:
        lines += [f"## {framework.name}", "", f"{framework.source}. Source: {framework.link}", ""]
        if framework.note:
            lines += [framework.note, ""]
        lines += ["| Control | Label | Evidence |", "|---|---|---|"]
        for result in (r for r in assessment.results if r.framework is framework):
            lines.append(f"| {result.control.id}: {result.control.title} | {LABELS[result.labels[level]]} | "
                         f"{result.summary().replace('|', '/')} |")
        lines.append("")
    other = [lv for lv in RISK_LEVELS if lv != level]
    lines += ["## At other risk levels", ""]
    for lv in other:
        changed = [r for r in assessment.results if r.labels[lv] != r.labels[level]]
        gaps = len(assessment.not_shown(lv))
        lines.append(f"- **{lv}**: {len(changed)} controls change label; {gaps} would apply and not be shown to be met.")
    lines += ["", f"_{DISCLAIMER} Generated by {data['generated_by']}._", ""]
    return "\n".join(lines)


def render_html(assessment: Assessment) -> str:
    data = report_data(assessment)
    payload = json.dumps(data, ensure_ascii=False).replace("</", "<\\/")
    return (TEMPLATE.read_text(encoding="utf-8").replace("__DATA__", payload)
            .replace("__TEAM__", _html(data["team"])).replace("__VERSION__", __version__)
            .replace("__RUN__", _html(data["run"]["id"])))


def write_report(assessment: Assessment, folder: Path) -> list[Path]:
    folder = Path(folder)
    folder.mkdir(parents=True, exist_ok=True)
    written = {"index.html": render_html(assessment), "evidence.md": render_markdown(assessment),
               "evidence.json": json.dumps(report_data(assessment), indent=2, ensure_ascii=False) + "\n"}
    for name, text in written.items():
        (folder / name).write_text(text, encoding="utf-8")
    return [folder / name for name in written]


def _when(created_at: str) -> str:
    """2026-10-17T15:51:56+00:00 -> 17-10-2026, 15:51 UTC."""
    try:
        moment = datetime.fromisoformat(created_at).astimezone(timezone.utc)
    except (TypeError, ValueError):
        return str(created_at)
    return moment.strftime("%d-%m-%Y, %H:%M UTC")


def _html(text: str) -> str:
    return str(text).replace("&", "&amp;").replace("<", "&lt;").replace(">", "&gt;")
